    "",
    "### Priority Flags",
    "- [Action needed: ...]",
    "- [Overdue: ...]",
    "- [Risk: ...]",
    "",
    "### Pipeline",
    "- New leads: [X] | Hot leads: [X] | Conversions pending: [X]",
    "- [Brief update on any notable leads]",
    "",
    "### Clients",
    "- Active clients: [X]",
    "- [Any client needing attention or recent activity]",
    "",
    "### Finance",
    "- Outstanding invoices: [X] | Overdue: [X]",
    "- Cash position: [summary if available]",
    "",
    "### Tasks & Progress",
    "- Active tasks: [X]",
    "- [Key tasks in progress or completed yesterday]",
    "",
    "### Ideas & Strategy",
    "- [Any active ideas or strategies in progress]",
    "",
    "### Today's Focus",
    "1. [Most important thing to address]",
    "2. [Second priority]",
    "3. [Third priority]",
