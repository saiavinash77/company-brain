    "",
    "## Weekly Briefing Format",
    "```",
    "## Weekly Recap — [Week ending Date]",
    "",
    "### Week Highlights",
    "- [Key wins and accomplishments]",
    "",
    "### Metrics",
    "| Metric | This Week | Last Week | Change |",
    "|--------|-----------|-----------|--------|",
    "| Leads  | [X]       | [X]       | [+/-X] |",
    "| Clients | [X]      | [X]       | [+/-X] |",
