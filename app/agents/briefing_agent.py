def create_briefing_agent() -> Agent:
    """Create the Briefing Agent for daily and weekly summaries."""
    return Agent(
        name="Briefing Agent",
        role="Compiles daily and weekly briefings summarizing business status across all areas",
        model=get_member_model(),
        instructions=BRIEFING_AGENT_INSTRUCTIONS,
        search_knowledge=True,
        markdown=True,
        metadata={"type": "briefing"},
    )
